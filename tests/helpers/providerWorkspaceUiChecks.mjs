import assert from 'node:assert/strict'

export async function assertProviderWorkspace(page, output) {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.evaluate(async () => {
    const { useAppStore } = await import('/src/store/index.ts')
    const settings = useAppStore.getState().settings
    useAppStore.setState({ settings: { ...settings, activeProviderId: 'local', providers: [
      { ...settings.providers[0], name: 'DeepSeek', defaultModel: 'deepseek-v4-pro', baseUrl: 'https://api.deepseek.com', contextWindow: 999424 },
      { id: 'cheap', name: 'Xiaomi Mimo', enabled: true, defaultModel: 'mimo-pro', baseUrl: 'https://example.invalid/v1', apiKey: '', allowSubagents: true },
      { id: 'offline', name: 'Local Ollama', enabled: false, defaultModel: 'qwen', baseUrl: 'http://localhost:11434/v1', apiKey: '' }
    ] } })
    useAppStore.getState().setTheme('light')
    window.api.provider.listModels = async () => ({ models: [{ id: 'deepseek-v4-pro' }, { id: 'deepseek-v4-flash' }] })
  })
  await page.locator('.sidebar').getByText('设置', { exact: true }).click()
  await page.getByRole('tab', { name: 'LLM 提供商', exact: true }).click()
  const directory = page.locator('.provider-directory')
  const name = page.getByRole('textbox', { name: '名称', exact: true })
  assert.equal(await directory.locator('.provider-directory-item').count(), 3)
  assert.equal(await page.locator('.provider-editor').count(), 1)
  await directory.getByRole('button', { name: /Xiaomi Mimo/ }).click()
  await name.fill('Mimo draft')
  await page.locator('.provider-connection summary').click()
  const headers = page.getByRole('textbox', { name: '自定义请求头（可选）', exact: true })
  await headers.fill('Invalid header')
  assert.equal(await page.getByRole('button', { name: '保存设置', exact: true }).isDisabled(), true)
  await directory.getByRole('button', { name: /DeepSeek/ }).click()
  await directory.getByRole('button', { name: /Mimo draft/ }).click()
  assert.equal(await name.inputValue(), 'Mimo draft', 'provider switching preserves unsaved fields')
  assert.equal(await headers.inputValue(), 'Invalid header', 'invalid advanced drafts survive switching and remain visible')
  await headers.fill('X-Tenant: demo')
  await page.locator('.provider-editor-actions .btn-ghost').click()
  assert.match(await directory.getByRole('button', { name: /Mimo draft/ }).innerText(), /当前/)
  await directory.getByRole('button', { name: /DeepSeek/ }).click()
  assert.match(await directory.getByRole('button', { name: /Mimo draft/ }).innerText(), /当前/, 'selection does not change the default provider')
  await page.getByRole('button', { name: '刷新模型列表', exact: true }).click()
  await page.getByRole('option', { name: 'deepseek-v4-flash', exact: true }).click()
  assert.equal(await page.getByRole('textbox', { name: '默认模型', exact: true }).inputValue(), 'deepseek-v4-flash')
  await page.getByRole('textbox', { name: '默认模型', exact: true }).fill('deepseek-v4-pro')
  await page.locator('.model-list-backdrop').click()
  await page.getByRole('textbox', { name: '名称', exact: true }).click()
  await page.locator('.provider-generation summary').click()
  await page.getByRole('combobox', { name: '思考强度协议', exact: true }).selectOption('deepseek')
  await page.locator('.provider-generation summary').click()
  await page.getByRole('checkbox', { name: '允许子 Agent 使用', exact: true }).uncheck()
  await page.getByRole('spinbutton', { name: '并发上限', exact: true }).fill('3')
  await page.locator('.settings-view').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: `${output}/provider-workspace-light.png` })
  await page.evaluate(async () => { const { useAppStore } = await import('/src/store/index.ts'); useAppStore.getState().setTheme('dark') })
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
  await page.screenshot({ path: `${output}/provider-workspace-dark.png` })
  await page.setViewportSize({ width: 900, height: 900 })
  await page.screenshot({ path: `${output}/provider-workspace-narrow.png` })
  assert.ok(await page.locator('.provider-workspace').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'narrow layout has no horizontal form overflow')
  assert.ok(await page.locator('.provider-editor').evaluate(el => el.getBoundingClientRect().right <= innerWidth), 'editor stays inside the minimum supported app width')
  await page.getByRole('button', { name: '保存设置', exact: true }).click()
  await page.locator('.conversation-flow').waitFor()
  const saved = await page.evaluate(async () => {
    const { useAppStore } = await import('/src/store/index.ts'); return useAppStore.getState().settings
  })
  assert.equal(saved.activeProviderId, 'cheap')
  assert.equal(saved.providers[0].reasoningDialect, 'deepseek')
  assert.equal(saved.providers[0].allowSubagents, false)
  assert.equal(saved.providers[0].maxConcurrency, 3)
  assert.deepEqual(saved.providers[1].headers, { 'x-tenant': 'demo' })
  await page.locator('.sidebar').getByText('设置', { exact: true }).click()
  await page.getByRole('button', { name: '添加提供商', exact: true }).click()
  assert.equal(await name.inputValue(), 'New Provider')
  assert.equal(await directory.locator('.provider-directory-item').count(), 4)
  await page.getByRole('button', { name: '移除', exact: true }).click()
  assert.equal(await directory.locator('.provider-directory-item').count(), 3)
}
