import assert from 'node:assert/strict'
import { classifySubagentFailure, continuationPrompt, subagentRecovery } from '../src/main/agent/subagentRecovery.ts'
import { SubagentRunDiagnostics } from '../src/main/agent/subagentDiagnostics.ts'
import { createMcpTaskSession } from '../src/main/agent/taskProtocol.ts'

const failure = (kind: ReturnType<typeof classifySubagentFailure>['kind']) => ({ kind, stage: 'runtime' as const })
assert.equal(classifySubagentFailure(Object.assign(new Error('fetch failed'), { cause: { code: 'ECONNRESET' } }), 'runtime').kind, 'network')
assert.equal(classifySubagentFailure(Object.assign(new Error('fetch failed'), { cause: { code: 'ETIMEDOUT' } }), 'runtime').kind, 'timeout')
assert.equal(classifySubagentFailure(new Error('LLM stream idle timeout: no data'), 'runtime').kind, 'timeout')
assert.equal(classifySubagentFailure(Object.assign(new Error('limit'), { status: 429 }), 'runtime').kind, 'rate_limit')
assert.equal(classifySubagentFailure(Object.assign(new Error('unavailable'), { status: 503 }), 'runtime').kind, 'provider_unavailable')
assert.equal(classifySubagentFailure(Object.assign(new Error('key'), { status: 401 }), 'startup').kind, 'configuration')
assert.equal(classifySubagentFailure(Object.assign(new Error('network token timed out'), { status: 401 }), 'runtime').kind, 'configuration')
assert.equal(classifySubagentFailure(Object.assign(new Error('budget'), { name: 'ContextBudgetExceededError' }), 'runtime').kind, 'context_limit')
assert.equal(classifySubagentFailure(Object.assign(new Error('maximum context length exceeded'), { status: 400 }), 'runtime').kind, 'context_limit')
assert.equal(classifySubagentFailure(new Error('unknown'), 'runtime').kind, 'unknown')
for (const status of ['running', 'busy', 'failed'] as const) assert.equal(subagentRecovery(status, false, true, failure('network')).continuation_ready, false)
assert.equal(subagentRecovery('awaiting_permission', false, true).next_action, 'await_permission')
assert.equal(subagentRecovery('failed', true, true, failure('network')).next_action, 'continue_subagent')
assert.equal(subagentRecovery('failed', true, true, failure('network'), 'network').next_action, 'inspect_failure')
assert.equal(subagentRecovery('failed', true, true, failure('configuration')).retry_recommended, false)
assert.equal(subagentRecovery('failed', true, true, failure('context_limit')).next_action, 'reduce_context')
assert.equal(subagentRecovery('aborted', true, true).next_action, 'respect_cancellation')
assert.equal(subagentRecovery('completed', true, true).next_action, 'review_result')
assert.equal(subagentRecovery('completed', true, false).continuation_ready, false)
assert.match(continuationPrompt('finish the check', 'failed', 'original goal'), /original goal/)
assert.match(continuationPrompt('finish', 'failed'), /avoid repeating commands/)

const task = createMcpTaskSession('turn-2')
const diagnostics = new SubagentRunDiagnostics({ runNumber: 1, taskId: 'turn-1', failure: 'network' })
const events = diagnostics.events(task)
events.retry!('s', 1, 3, new Error('network failed'))
let view = diagnostics.snapshot('running', false, true)
assert.equal(view.diagnostics.phase, 'retrying'); assert.equal(view.recovery.continuation_ready, false)
assert.equal(view.diagnostics.run_number, 2); assert.equal(view.diagnostics.continued_from_task_id, 'turn-1')
events.reasoning!('s', 'm', 'PRIVATE REASONING')
assert.equal(diagnostics.snapshot('running', false, true).diagnostics.phase, 'reasoning')
events.error!('s', new Error('network failed'))
view = diagnostics.snapshot('failed', true, true)
assert.equal(view.diagnostics.failure!.kind, 'network'); assert.equal(view.recovery.repeated_failure_kind, true)
assert.doesNotMatch(JSON.stringify(view), /PRIVATE|network failed/)
view.diagnostics.failure!.kind = 'unknown'
assert.equal(diagnostics.failureKind(), 'network', 'returned projections cannot mutate owned diagnostic state')
events.error!('s', new Error('unknown late failure'))
assert.equal(diagnostics.failureKind(), 'network')

const empty = createMcpTaskSession('empty'); const emptyDiagnostics = new SubagentRunDiagnostics()
emptyDiagnostics.events(empty).complete!('s', 'm', '  ')
assert.equal(empty.status().status, 'failed'); assert.equal(emptyDiagnostics.failureKind(), 'no_deliverable')
console.log('Subagent recovery: failure classification, settled/latest gates, repeated failures, cancellation, safe bounded diagnostics and missing deliverables passed')
